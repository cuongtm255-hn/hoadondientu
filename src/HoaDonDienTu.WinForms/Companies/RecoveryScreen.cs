using System;
using System.Threading;
using System.Threading.Tasks;
using System.Windows.Forms;
using HoaDonDienTu.Application.Navigation;
using HoaDonDienTu.WinForms.Navigation;

namespace HoaDonDienTu.WinForms.Companies
{
    /// <summary>Screen khôi phục danh mục doanh nghiệp: control + presenter.</summary>
    public sealed class RecoveryScreen : IScreen
    {
        private readonly RecoveryControl _control;
        private readonly RecoveryPresenter _presenter;

        public RecoveryScreen(RecoveryControl control, Func<IRecoveryView, RecoveryPresenter> presenterFactory)
        {
            _control = control;
            _presenter = presenterFactory(control);
            _presenter.Initialize();
        }

        public ScreenId Id
        {
            get { return ScreenId.Recovery; }
        }

        public Control View
        {
            get { return _control; }
        }

        public Task<bool> CanCloseAsync(CancellationToken cancellationToken)
        {
            return Task.FromResult(true);
        }

        public void CancelOperations()
        {
        }

        public void Dispose()
        {
            _presenter.Dispose();
            _control.Dispose();
        }
    }
}
